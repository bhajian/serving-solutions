def dump(path, docs, header=HEADER):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + '\n---\n'.join(yaml.safe_dump(d, sort_keys=False, width=110) for d in docs))


def config_overlay(exp, name, model, topology, layout=None, extra_args=None, frontend_args=None, env=None,
                   components=()):
    """One serving configuration: rendered graph + namespace bundle + site patches."""
    p = rg.PROFILES[model]
    g = rg.graph(model, p, topology, layout, extra_args)
    g['metadata']['annotations']['serving-solutions/experiment'] = f'{exp}/{name}'
    if frontend_args is not None:
        g['spec']['components'][0]['podTemplate']['spec']['containers'][0]['args'] = frontend_args
    for comp, pairs in (env or {}).items():
        for c in g['spec']['components']:
            if c['name'] == comp:
                for e in c['podTemplate']['spec']['containers'][0]['env']:
                    if e['name'] in pairs:
                        e['value'] = pairs[e['name']]
    d = OUT / exp / 'configs' / name
    dump(d / 'graph.yaml', [g])
    k = {'apiVersion': 'kustomize.config.k8s.io/v1beta1', 'kind': 'Kustomization', 'namespace': model,
         'resources': ['graph.yaml', os.path.relpath(TRACK / f'production/{model}-h200/namespace', PLANNED / exp / 'configs' / name)],
         'components': [os.path.relpath(TRACK / 'common', PLANNED / exp / 'configs' / name), *components],
         'patches': [{'target': {'group': 'nvidia.com', 'version': 'v1beta1', 'kind': 'DynamoGraphDeployment',
                                 'name': model},
                      'patch': yaml.safe_dump(site_patches(model, topology, SITES['h200']), sort_keys=False)}]}
    dump(d / 'kustomization.yaml', [k])
    return f'tracks/nvidia-dynamo/studies/planned/{exp}/configs/{name}'


def frontend(workers, weight='8000', mode='kv', extra=()):
    args = ['-m', 'dynamo.frontend', '--http-port', '8000', '--router-mode', mode,
            '--router-min-initial-workers', str(workers)]
    if mode == 'kv':
        args += ['--router-decode-active-request-weight', weight, '--router-replica-sync']
    return args + list(extra)


def sweep_spec(exp, configs, rps, dataset, duration=480, model='nemotron-3-nano'):
    return {'study': exp, 'results': f'/bench/results/{exp}', 'local_records': f'build/experiments/{exp}',
            'dataset': f'/bench/{Path(dataset).name}', 'model': rg.PROFILES[model]['model_id'], 'namespace': model,
            'metrics_selector': f'nvidia.com/dynamo-graph-deployment-name={model},nvidia.com/dynamo-component-type in (worker,prefill,decode)',
            'gpu_count': 16, 'gpu_hour_usd': 0, 'slo': SLO, 'rps': rps,
            'loadgen': {'arrival': 'poisson', 'duration': duration, 'processes': 16, 'max_model_len': 262144,
                        'deployment': f'/bench/{model}-deployment.json'},
            'configs': [{'name': n, 'overlay': f'build/site/{path}', 'technology': tech, 'base_url': FRONTEND,
                         'topology': topo, 'wait': f'dynamographdeployment/{model} -n {model}'}
                        for n, path, tech, topo in configs]}


